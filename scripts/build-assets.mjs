// One-off asset builder for the home page.
//  1. lib/world-dots.ts: a land mask sampled on a lon/lat grid from Natural
//     Earth 110m land (world-atlas), packed as one hex string per row.
//  2. public/brand/logo-reversed.png: the brand logo with the navy wordmark
//     turned white, so it reads on the navy hero banner. The disc is untouched.
import fs from "node:fs";
import { createRequire } from "node:module";
import { feature } from "topojson-client";
import sharp from "sharp";

const require = createRequire(import.meta.url);
const topo = require("world-atlas/land-110m.json");
const land = feature(topo, topo.objects.land);

const polys = [];
for (const f of land.features) {
  const g = f.geometry;
  if (g.type === "Polygon") polys.push(g.coordinates);
  else for (const p of g.coordinates) polys.push(p);
}
const bbox = polys.map((rings) => {
  let x0 = 180, x1 = -180, y0 = 90, y1 = -90;
  for (const [x, y] of rings[0]) { x0 = Math.min(x0, x); x1 = Math.max(x1, x); y0 = Math.min(y0, y); y1 = Math.max(y1, y); }
  return [x0, y0, x1, y1];
});
const inRing = (ring, x, y) => {
  let c = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i], [xj, yj] = ring[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) c = !c;
  }
  return c;
};
const isLand = (x, y) => {
  for (let k = 0; k < polys.length; k++) {
    const b = bbox[k];
    if (x < b[0] || x > b[2] || y < b[1] || y > b[3]) continue;
    if (inRing(polys[k][0], x, y) && !polys[k].slice(1).some((h) => inRing(h, x, y))) return true;
  }
  return false;
};

const STEP = 1.5; // degrees
const cols = Math.round(360 / STEP);
const LAT_TOP = 78, LAT_BOTTOM = -58;
const rows = Math.round((LAT_TOP - LAT_BOTTOM) / STEP);
const hex = [];
let count = 0;
for (let r = 0; r < rows; r++) {
  const lat = LAT_TOP - (r + 0.5) * STEP;
  let bits = "";
  for (let c = 0; c < cols; c++) {
    const lon = -180 + (c + 0.5) * STEP;
    const on = isLand(lon, lat);
    if (on) count++;
    bits += on ? "1" : "0";
  }
  while (bits.length % 4) bits += "0";
  let h = "";
  for (let i = 0; i < bits.length; i += 4) h += parseInt(bits.slice(i, i + 4), 2).toString(16);
  hex.push(h);
}
const ts = `// Generated by scripts/build-assets.mjs from Natural Earth 110m land (world-atlas).
// A ${STEP}° lon/lat land mask, one hex string per row from north to south.
export const LAND = {
  step: ${STEP},
  cols: ${cols},
  rows: ${rows},
  latTop: ${LAT_TOP},
  hex: ${JSON.stringify(hex)},
} as const;

/** Every land cell as [lon, lat] in degrees. */
export function landPoints(): [number, number][] {
  const out: [number, number][] = [];
  LAND.hex.forEach((row, r) => {
    const lat = LAND.latTop - (r + 0.5) * LAND.step;
    for (let c = 0; c < LAND.cols; c++) {
      const nib = parseInt(row[c >> 2], 16);
      if (nib & (8 >> (c & 3))) out.push([-180 + (c + 0.5) * LAND.step, lat]);
    }
  });
  return out;
}
`;
fs.writeFileSync("lib/world-dots.ts", ts);
console.log("land cells", count, "of", cols * rows);

// Reversed logo: wordmark pixels (right of the disc) become white.
const src = sharp("public/brand/logo.png");
const { data, info } = await src.raw().toBuffer({ resolveWithObject: true });
const discEdge = Math.round(info.width * 0.225);
for (let y = 0; y < info.height; y++) {
  for (let x = discEdge; x < info.width; x++) {
    const i = (y * info.width + x) * 4;
    if (data[i + 3] > 0) { data[i] = 255; data[i + 1] = 255; data[i + 2] = 255; }
  }
}
await sharp(data, { raw: info }).png().toFile("public/brand/logo-reversed.png");
console.log("logo-reversed.png", info.width, "x", info.height);
